#
# Embed OpenCL kernel sources into a C++ registry (.inc).
#
# 用法:
#   embed_kernel.py --kernels <kernels 目录> --out <生成文件> <a.cl> [<b.cl> ...]
#
# 生成内容:
#   static const ocl_kernel_src g_kernel_srcs[] = {
#   { "add/kernel_add_f16",
#   R"(...)" R"(...)" },
#   ...
#   };
#
# 注册表 id = 相对 kernels 目录的路径去掉 .cl, 例如 "mul_mat/gemv_f16_f16"。
#

import argparse
import os
import sys


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--kernels", required=True, help="kernel source root (kernels/)")
    ap.add_argument("--out", required=True, help="generated .inc file")
    ap.add_argument("srcs", nargs="+", help=".cl source files")
    args = ap.parse_args()

    root = os.path.abspath(args.kernels)

    with open(args.out, "w") as out:
        out.write("// generated by embed_kernel.py; do not edit\n")
        out.write("static const ocl_kernel_src g_kernel_srcs[] = {\n")
        for src in args.srcs:
            rel = os.path.relpath(os.path.abspath(src), root)
            if not rel.endswith(".cl"):
                sys.exit("unexpected kernel source: %s" % src)

            kid = rel[:-3].replace(os.sep, "/")
            out.write('{ "%s",\n' % kid)
            with open(src, "r") as f:
                for line in f:
                    if ')"' in line:
                        sys.exit("%s: line contains ')\"'" % src)
                    out.write('R"({})"\n'.format(line))
            out.write("},\n")
        out.write("};\n")


if __name__ == "__main__":
    main()
